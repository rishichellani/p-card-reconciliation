# --------------------------------------------------------------------------- data
def list_runs() -> list[str]:
    if not OUTPUT.exists():
        return []
    return sorted((d.name for d in OUTPUT.iterdir() if (d / STAGE_FILES[4]).exists()), reverse=True)


@st.cache_data(show_spinner=False)
def load_run(run_id: str) -> dict:
    d = OUTPUT / run_id
    env = {s: json.loads((d / STAGE_FILES[s]).read_text()) for s in (1, 2, 3)}
    return {
        "env": env,
        "journal": pd.read_csv(d / STAGE_FILES[4], dtype={"gl_account": str, "cost_center": str}),
        "manifest": json.loads((d / CSV_MANIFEST).read_text()),
        "log": (d / "pipeline.log").read_text() if (d / "pipeline.log").exists() else "",
        "problems": verify_run(d),
    }


def txn_frame(items: list[dict]) -> pd.DataFrame:
    rows = []
    for a in items:
        r, t = a["justified"]["routed"], a["justified"]["routed"]["transaction"]
        llm = a.get("llm_result") or {}
        rows.append({
            "txn_id": a["txn_id"], "date": t["post_date"], "employee": r["employee_name"],
            "merchant": t["merchant_name"].title(), "category": a["category"].replace("_", " ").title(),
            "amount": float(t["amount"]), "rules": STATUS[a["deterministic_status"]][0],
            "llm": (llm.get("verdict") or "-").title() if llm else "-", "status_key": a["final_status"],
            "status": STATUS[a["final_status"]][0],
            "findings": ", ".join(f["code"] for f in a["findings"] if f["severity"] != "INFO"),
            "served_by": llm.get("served_by") or "",
        })
    return pd.DataFrame(rows)


